"""assets/ui/*.png -> src/playshell_icons.h (PNG bytes; the home screen module decodes them)."""
import os
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names = ['playshell', 'cross', 'circle', 'r3', 'console_gb', 'console_gbc', 'console_nes', 'console_gg', 'console_ps1', 'console_snes', 'console_gba', 'console_nds', 'console_dos', 'console_n64', 'console_pce', 'console_ws', 'console_3ds', 'arrow_up', 'arrow_down'] + sorted(
    f[:-4] for f in os.listdir(os.path.join(HERE, 'assets', 'ui')) if f.startswith('bezel_') and f[6].isdigit())  # tools/make_bezels.py
out = ['// PlayShell\'s pictures (PNG, drawn for PlayShell), decoded by the home screen module.',
       '// Generated by tools/make_icons.py - not edited by hand.', '#pragma once', '']
for n in names:
    d = open(os.path.join(HERE, 'assets', 'ui', n + '.png'), 'rb').read()
    out.append('static const unsigned char kPic_%s[%d] = {' % (n, len(d)))
    for i in range(0, len(d), 24):
        out.append('\t' + ','.join('0x%02x' % b for b in d[i:i + 24]) + ',')
    out += ['};', '']
out.append('struct Pic { const char* name; const unsigned char* png; unsigned size; };')
out.append('static const Pic kPics[] = {' + ', '.join('{"%s", kPic_%s, sizeof(kPic_%s)}' % (n, n, n) for n in names) + '};')
out.append('')
open(os.path.join(HERE, 'src', 'playshell_icons.h'), 'w', newline='\n').write('\n'.join(out))
print('ok')

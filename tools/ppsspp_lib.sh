#!/usr/bin/env bash
# Builds PPSSPP's libretro core (GPL-2.0+, github.com/hrydgard/ppsspp) as a static library for the PS5:
#   PPSSPP=/path/to/ppsspp tools/ppsspp_lib.sh      -> $WORK/libppsspp.a      (compile test: KEEP_GOING=1)
# Without FFmpeg (PPSSPP's own Atrac3+ decoder plays the music; videos need FFmpeg). Software renderer + x86-64 JIT.
set -e
PPSSPP="${PPSSPP:-${REF:-$HOME/ps5/ref}/ppsspp}" # (REF: where the emulator sources are)
SDK="${PS5_PAYLOAD_SDK:-$HOME/ps5/wallpaper/sdk-upstream}"
WORK="${WORK:-$HOME/ps5/ppsspp-build}"
mkdir -p "$WORK"
rsync -a --delete --exclude .git --exclude pspautotests --exclude frametests "$PPSSPP/" "$WORK/src/"
# PlayShell's changes to the copy (the source stays as it is):
#  - at most 8 worker threads: its CPU count (CPUID, made for PCs) said 16 x 16 = 256 on the PS5, then asked for 512
#    threads - more than a payload may have (PlayShell died at "ThreadManager::Init(compute threads: 256")
sed -i 's|numComputeThreads_ = numRealCores \* numLogicalCoresPerCpu;|numComputeThreads_ = std::max(1, std::min(numRealCores * numLogicalCoresPerCpu, 8)); // PlayShell: PS5|' 	"$WORK/src/Common/Thread/ThreadManager.cpp"
grep -q 'PlayShell: PS5' "$WORK/src/Common/Thread/ThreadManager.cpp" || { echo "patch: ThreadManager not changed"; exit 1; }
cd "$WORK/src/libretro"
# the SDK is FreeBSD's libc (see pcsx_lib.sh); runnable memory through the kernel (ps_mmap / ps_mprotect)
# (tools/compat: ps5_compat.h first into every file; the OpenGL headers - GL code compiles but never runs, software
# rendering - taken from the build machine's Mesa headers)
HERE="$(cd "$(dirname "$0")" && pwd)"
mkdir -p "$WORK/compat/GL" "$WORK/compat/KHR"
cp "$HERE/compat/ps5_compat.h" "$WORK/compat/"
cp /usr/include/GL/gl.h /usr/include/GL/glext.h "$WORK/compat/GL/" && cp /usr/include/KHR/khrplatform.h "$WORK/compat/KHR/"
FLAGS="-march=znver2 -fPIC -fPIE -ffunction-sections -fdata-sections -w -I$WORK/compat -include $WORK/compat/ps5_compat.h"
FLAGS="$FLAGS -Dmmap=ps_mmap -Dmprotect=ps_mprotect"
make -f Makefile -j"$(nproc)" ${KEEP_GOING:+-k} platform=unix STATIC_LINKING=1 \
	CC="$SDK/bin/prospero-clang $FLAGS" CXX="$SDK/bin/prospero-clang++ $FLAGS" AR="$SDK/bin/llvm-ar" CPUOPTS="-O3 -DNDEBUG" "$@" \
	> "$WORK/build.log" 2>&1 || true
echo "errors: $(grep -c 'error:' "$WORK/build.log")"
grep -E "error:" "$WORK/build.log" | sed -E 's/^[^ ]+ error: //' | sort | uniq -c | sort -rn | head -25
grep -E "error:" "$WORK/build.log" | awk -F: '{print $1}' | sort -u | head -30
if [ -f "$WORK/src/libretro/ppsspp_libretro.so" ] && [ -z "$KEEP_GOING" ]; then
	cp "$WORK/src/libretro/ppsspp_libretro.so" "$WORK/libppsspp.a" # (an archive: STATIC_LINKING keeps the .so name)
	# zstd's assembly decoder went into the archive as its source file: assembled here, put in its place
	ASM="$(find "$WORK/src/ext/zstd" -name huf_decompress_amd64.S | head -1)"
	if [ -n "$ASM" ] && "$SDK/bin/llvm-ar" t "$WORK/libppsspp.a" | grep -q '^huf_decompress_amd64.S$'; then
		"$SDK/bin/llvm-ar" d "$WORK/libppsspp.a" huf_decompress_amd64.S
		"$SDK/bin/prospero-clang" -march=znver2 -fPIC -fPIE -c "$ASM" -o "$WORK/huf_decompress_amd64.o"
		"$SDK/bin/llvm-ar" rs "$WORK/libppsspp.a" "$WORK/huf_decompress_amd64.o"
	fi
	bash "$HERE/prefix_lib.sh" "$WORK/libppsspp.a" psp_                # retro_run -> psp_retro_run, ...
	ls -la "$WORK/libppsspp.a"
	# zlib: on Linux PPSSPP takes the system's - here its own copy (ext/zlib), as libz.a
	mkdir -p "$WORK/zlib"
	for f in "$WORK"/src/ext/zlib/*.c; do
		"$SDK/bin/prospero-clang" -O2 -march=znver2 -fPIC -fPIE -ffunction-sections -fdata-sections -w -I"$WORK/src/ext/zlib" 			-c "$f" -o "$WORK/zlib/$(basename "$f" .c).o"
	done
	rm -f "$WORK/libz.a" && "$SDK/bin/llvm-ar" rcs "$WORK/libz.a" "$WORK"/zlib/*.o
	# OpenGL: PPSSPP's GL code is built but never runs (software rendering) - empty stand-ins for what it calls
	"$SDK/bin/llvm-nm" -u "$WORK/libppsspp.a" 2>/dev/null | awk '$1 == "U" && $2 ~ /^gl[A-Z]/ {print $2}' | sort -u |
		awk 'BEGIN {print "/* generated by tools/ppsspp_lib.sh: never called (PPSSPP draws in software here) */"}
		     {print "void " $1 "(void) {}"}' > "$WORK/glstub.c"
	"$SDK/bin/prospero-clang" -O2 -fPIC -fPIE -c "$WORK/glstub.c" -o "$WORK/glstub.o"
	rm -f "$WORK/libglstub.a" && "$SDK/bin/llvm-ar" rcs "$WORK/libglstub.a" "$WORK/glstub.o"
	echo "zlib + $(grep -c '^void' "$WORK/glstub.c") OpenGL stand-ins built"
fi

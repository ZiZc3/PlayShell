#!/usr/bin/env bash
# One set of empty OpenGL stand-ins for every core in playshell.elf (their GL code is built but never runs: the cores
# render on the CPU here): the gl* names PPSSPP and the cores (~/ps5/cores/*/gl.list) call -> ~/ps5/cores/libglstub.a
set -e
SDK="${PS5_PAYLOAD_SDK:-$HOME/ps5/wallpaper/sdk-upstream}"
OUT="$HOME/ps5/cores"
mkdir -p "$OUT"
{ "$SDK/bin/llvm-nm" -u "$HOME/ps5/ppsspp-build/libppsspp.a" 2>/dev/null | awk '$1 == "U" && $2 ~ /^gl[A-Z]/ {print $2}'
  cat "$OUT"/*/gl.list 2>/dev/null; } | sort -u |
	awk 'BEGIN {print "/* generated by tools/glstub.sh: never called (the cores render on the CPU here) */"}
	     {print "void " $1 "(void) {}"}' > "$OUT/glstub.c"
"$SDK/bin/prospero-clang" -O2 -fPIC -fPIE -c "$OUT/glstub.c" -o "$OUT/glstub.o"
rm -f "$OUT/libglstub.a" && "$SDK/bin/llvm-ar" rcs "$OUT/libglstub.a" "$OUT/glstub.o"
echo "glstub: $(grep -c '^void' "$OUT/glstub.c") OpenGL stand-ins -> $OUT/libglstub.a"
